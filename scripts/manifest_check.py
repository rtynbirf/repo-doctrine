#!/usr/bin/env python3
# Волна ×6 · 6-D · repo-doctrine#24 — T17 «Манифест свежести: генерится, а не пишется».
# Прецедент ci#16 институционализируется: манифест checksums — генерат, не рукопись.
#   build — пересобрать MANIFEST_SHA256.txt (единственный законный способ его менять);
#   check — гейт CI: пересборка в память + сравнение. Манифеста нет, стёрта шапка
#           GENERATED (ручная правка) или расхождение строк — красный с точным приговором.
# Честная граница: «живые файлы» (PULSE.md — журнал ПУЛЬС-воркфлоу; mutations.yaml и
# demo-badge.md — реестр идемпотентность-храповика; сам манифест) ведутся машинами и
# в заморозку не входят — граница объявлена в шапке манифеста, не спрятана.
# stdlib-only, офлайн, 3.10+. Формат строки: "<sha256>  <путь>" (совместим с sha256sum -c).
import argparse, hashlib, os, subprocess, sys

MANIFEST = "MANIFEST_SHA256.txt"
REF = "repo-doctrine#24"
HEADER_MARK = "# GENERATED by make manifest"
HEADER = [
    HEADER_MARK + " — файл генерится машиной, правка руками = красный гейта manifest-freshness.",
    "# Пересборка: make manifest. Гейт: make manifest-check (%s)." % REF,
    "# Алгоритм: sha256, формат строки: <sha256>  <путь>, сортировка по пути (кодепоинтная).",
    "# Живые файлы (ведутся воркфлоу, в заморозку не входят): MANIFEST_SHA256.txt, PULSE.md, mutations.yaml, demo-badge.md",
]
LIVING_FILES = ("MANIFEST_SHA256.txt", "PULSE.md", "mutations.yaml", "demo-badge.md")
SKIP_DIRS = (".git",)


def _tracked(root):
    """Пути отслеживаемых файлов (git ls-files); если git недоступен — обход каталога."""
    try:
        p = subprocess.run(["git", "ls-files", "-z"], cwd=root, capture_output=True, timeout=30)
        if p.returncode == 0 and p.stdout:
            names = p.stdout.decode("utf-8", "surrogateescape").split("\0")
            return [n.replace(os.sep, "/") for n in names if n]
    except (OSError, subprocess.TimeoutExpired):
        pass
    out = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for name in filenames:
            out.append(os.path.relpath(os.path.join(dirpath, name), root).replace(os.sep, "/"))
    return sorted(out)


def collect(root):
    """Пути для пломбы: отслеживаемые файлы минус живые файлы; существующие на диске."""
    paths = []
    for rel in _tracked(root):
        if rel in LIVING_FILES:
            continue
        full = os.path.join(root, rel)
        if os.path.isfile(full) and not os.path.islink(full):
            paths.append(rel)
    return sorted(paths)


def build_lines(root):
    lines = list(HEADER)
    for rel in collect(root):
        h = hashlib.sha256()
        with open(os.path.join(root, rel), "rb") as f:
            for chunk in iter(lambda: f.read(1 << 16), b""):
                h.update(chunk)
        lines.append("%s  %s" % (h.hexdigest(), rel))
    return lines


def cmd_build(root):
    text = "\n".join(build_lines(root)) + "\n"
    with open(os.path.join(root, MANIFEST), "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    n = text.count("\n") - len(HEADER)
    print("MANIFEST: записан %s — %d файлов под пломбой." % (MANIFEST, n))


def cmd_check(root):
    path = os.path.join(root, MANIFEST)
    if not os.path.isfile(path):
        print("MANIFEST-FRESHNESS: КРАСНЫЙ — %s отсутствует. Пересборка: make manifest." % MANIFEST)
        return 1
    old = open(path, encoding="utf-8", newline="").read().splitlines()
    if not old or not old[0].startswith(HEADER_MARK):
        print("MANIFEST-FRESHNESS: КРАСНЫЙ — ручная правка %s: нет шапки «%s»." % (MANIFEST, HEADER_MARK))
        print("Манифест — генерат, не рукопись. Пересборка: make manifest.")
        return 1
    new = build_lines(root)
    if old == new:
        print("MANIFEST-FRESHNESS: ЗЕЛЁНЫЙ — %s свеж: %d строк-пломб совпадают с пересборкой."
              % (MANIFEST, len(new) - len(HEADER)))
        return 0
    old_set, new_set = set(old), set(new)
    print("MANIFEST-FRESHNESS: КРАСНЫЙ — манифест устарел: содержимое репо изменилось после последней пересборки.")
    for l in sorted(new_set - old_set)[:20]:
        print("  + %s" % l)
    for l in sorted(old_set - new_set)[:20]:
        print("  - %s" % l)
    print("Приговор: пересобери манифест — make manifest — и закоммить обновлённый %s." % MANIFEST)
    return 1


def main():
    ap = argparse.ArgumentParser(
        description="Манифест свежести: генерится, а не пишется (%s)" % REF)
    ap.add_argument("cmd", choices=("build", "check"))
    ap.add_argument("--root", default=".", help="корень репо (по умолчанию — текущий)")
    a = ap.parse_args()
    sys.exit(cmd_build(a.root) if a.cmd == "build" else cmd_check(a.root))


if __name__ == "__main__":
    main()
